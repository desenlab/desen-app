const WORKSPACE_ROOT = path.resolve(PACKAGE_ROOT, "../..");
const require = createRequire(import.meta.url);

const AJV_VERSION = "8.20.0";
const PRETTIER_VERSION = "3.9.6";
const DRAFT_2020_12_ID = "https://json-schema.org/draft/2020-12/schema";
const EXPORT_NAME = "validatePackagePreflightCatalogGuard";
const STANDALONE_RUNTIME_IMPORT =
  'import { unicodeLength } from "../../bundle-verification-standalone-runtime.js";';
const STANDALONE_RUNTIME_SPECIFIER = "../../bundle-verification-standalone-runtime.js";
const EXPECTED_RUNTIME_HELPERS = Object.freeze(
  new Map([["ajv/dist/runtime/ucs2length", "unicodeLength"]]),
);
const AJV_OPTIONS = Object.freeze({
  allErrors: false,
  ownProperties: true,
  strictSchema: true,
  strictNumbers: true,
  strictTypes: false,
  strictTuples: false,
  strictRequired: false,
  validateFormats: false,
  removeAdditional: false,
  useDefaults: false,
  coerceTypes: false,
  code: Object.freeze({ source: true, esm: true, lines: true, optimize: 2 }),
});
const GENERATED_BANNER = `/* eslint-disable -- Generated from one reviewed, frozen JSON Schema. */
// @ts-nocheck
/**
 * Deterministic Ajv ${AJV_VERSION} fail-fast Catalog guard for M07-T03 package preflight.
 *
 * Do not edit this file by hand. Regenerate it from the frozen DESEN 0.1.0 Catalog schema.
 * Runtime package preflight does not compile schemas, evaluate code, resolve files, or use a network.
 */`;

export const DEFAULT_PACKAGE_PREFLIGHT_CATALOG_SCHEMA_PATH = path.join(
  WORKSPACE_ROOT,
  "packages/protocol/upstream/0.1.0/snapshot/schemas/desen-catalog.schema.json",
);

export const DEFAULT_PACKAGE_PREFLIGHT_CATALOG_GUARD_PATH = path.join(
  PACKAGE_ROOT,
  "src/generated/0.1.0/package-preflight-catalog-guard.ts",
);

export const PACKAGE_PREFLIGHT_CATALOG_SCHEMA_SPEC = Object.freeze({
  schemaFile: "desen-catalog.schema.json",
  schemaId: "https://schemas.desen.dev/0.1/desen-catalog.schema.json",
  schemaTitle: "DESEN Capability Catalog",
  schemaSha256: "51014ab088b6a483502fd6aee5eed9fc4451be55556b6bd6220a5a6a1b610555",
  exportName: EXPORT_NAME,
});

export class PackagePreflightCatalogGuardCodegenError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = "PackagePreflightCatalogGuardCodegenError";
    this.code = code;
    this.details = Object.freeze({ ...details });
  }
}

function fail(code, message, details = {}) {
  throw new PackagePreflightCatalogGuardCodegenError(code, message, details);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function compareStrings(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function assertToolVersions() {
  const actual = Object.freeze({
    ajv: require("ajv/package.json").version,
    prettier: require("prettier/package.json").version,
  });
  const expected = Object.freeze({ ajv: AJV_VERSION, prettier: PRETTIER_VERSION });
  if (actual.ajv !== expected.ajv || actual.prettier !== expected.prettier) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_TOOL_VERSION_MISMATCH",
      "Catalog guard generation requires the exact reviewed tool versions.",
      { expected, actual },
    );
  }
}

function auditSchemaReferences(schema) {
  const pending = [{ value: schema, pointer: "#" }];
  while (pending.length > 0) {
    const current = pending.pop();
    if (current === undefined) break;
    if (current.value === null || typeof current.value !== "object") continue;
    if (!Array.isArray(current.value)) {
      for (const keyword of ["$ref", "$dynamicRef"]) {
        const reference = current.value[keyword];
        if (typeof reference === "string" && reference !== "" && !reference.startsWith("#")) {
          fail(
            "PACKAGE_PREFLIGHT_CATALOG_GUARD_EXTERNAL_REFERENCE_FORBIDDEN",
            "The frozen Catalog schema may not resolve external references.",
            { pointer: `${current.pointer}/${keyword}`, reference },
          );
        }
      }
      if (Object.hasOwn(current.value, "$schema") && current.value.$schema !== DRAFT_2020_12_ID) {
        fail(
          "PACKAGE_PREFLIGHT_CATALOG_GUARD_DIALECT_MISMATCH",
          "The frozen Catalog schema changed its reviewed dialect.",
          { pointer: `${current.pointer}/$schema`, actual: current.value.$schema },
        );
      }
    }
    const entries = Array.isArray(current.value)
      ? current.value.map((child, index) => [String(index), child])
      : Object.entries(current.value);
    for (const [key, child] of entries.reverse()) {
      pending.push({
        value: child,
        pointer: `${current.pointer}/${key.replaceAll("~", "~0").replaceAll("/", "~1")}`,
      });
    }
  }
}

function parseAndAuditSchema(schemaBytes) {
  let schema;
  try {
    schema = JSON.parse(Buffer.from(schemaBytes).toString("utf8"));
  } catch {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_SCHEMA_PARSE_FAILED",
      "The frozen Catalog guard schema is not valid JSON.",
    );
  }
  const actualSha256 = sha256(schemaBytes);
  const spec = PACKAGE_PREFLIGHT_CATALOG_SCHEMA_SPEC;
  if (
    schema === null ||
    typeof schema !== "object" ||
    Array.isArray(schema) ||
    schema.$id !== spec.schemaId ||
    schema.$schema !== DRAFT_2020_12_ID ||
    schema.title !== spec.schemaTitle ||
    actualSha256 !== spec.schemaSha256
  ) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_SCHEMA_IDENTITY_MISMATCH",
      "The frozen Catalog guard schema changed exact bytes or identity.",
      {
        expected: {
          $id: spec.schemaId,
          $schema: DRAFT_2020_12_ID,
          title: spec.schemaTitle,
          sha256: spec.schemaSha256,
        },
        actual: {
          $id: schema?.$id,
          $schema: schema?.$schema,
          title: schema?.title,
          sha256: actualSha256,
        },
      },
    );
  }
  auditSchemaReferences(schema);
  return Object.freeze({ schema, actualSha256 });
}

function exportNames(source) {
  return [...source.matchAll(/^export\s+const\s+([A-Za-z_$][\w$]*)\s*=/gmu)].map(
    (match) => match[1],
  );
}

function assertExpectedExports(source) {
  const exports = exportNames(source);
  if (
    exports.length !== 1 ||
    exports[0] !== EXPORT_NAME ||
    [...source.matchAll(/^export\b/gmu)].length !== exports.length
  ) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_EXPORT_MISMATCH",
      "Standalone Catalog output must expose only the reviewed guard.",
      { expected: [EXPORT_NAME], actual: exports },
    );
  }
}

function assertNoExecutableLoading(source, phase) {
  const violations = [];
  if (/\brequire\s*\(/u.test(source)) violations.push("require");
  if (/\beval\s*\(/u.test(source)) violations.push("eval");
  if (/\bnew\s+Function\b/u.test(source)) violations.push("new-Function");
  if (/\bimport\s*\(/u.test(source)) violations.push("dynamic-import");
  if (
    source.includes(WORKSPACE_ROOT) ||
    source.includes(DEFAULT_PACKAGE_PREFLIGHT_CATALOG_SCHEMA_PATH) ||
    source.includes("file://")
  ) {
    violations.push("absolute-path");
  }
  const specifiers = [...source.matchAll(/\bfrom\s+["']([^"']+)["']/gu)].map((match) => match[1]);
  if (
    specifiers.some((specifier) => path.isAbsolute(specifier) || /^[A-Za-z]:[\\/]/u.test(specifier))
  ) {
    violations.push("absolute-module-path");
  }
  if (violations.length > 0) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_CODE_LOADING_VIOLATION",
      "Standalone Catalog output contains a forbidden loading construct.",
      { phase, violations: [...new Set(violations)].sort(compareStrings) },
    );
  }
}

function transformRuntimeHelpers(rawSource) {
  const requirePattern = /^const\s+([A-Za-z_$][\w$]*)\s*=\s*require\("([^"]+)"\)\.default;$/gmu;
  const matches = [...rawSource.matchAll(requirePattern)];
  const actual = matches.map((match) => match[2]).sort(compareStrings);
  const expected = [...EXPECTED_RUNTIME_HELPERS.keys()].sort(compareStrings);
  if (
    actual.length !== expected.length ||
    actual.some((helper, index) => helper !== expected[index])
  ) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_HELPER_MISMATCH",
      "Standalone Catalog output requested helpers outside the reviewed local allowlist.",
      { expected, actual },
    );
  }
  const body = rawSource.replace(requirePattern, (_line, binding, helper) => {
    const local = EXPECTED_RUNTIME_HELPERS.get(helper);
    if (local === undefined) {
      fail(
        "PACKAGE_PREFLIGHT_CATALOG_GUARD_HELPER_MISMATCH",
        "Standalone Catalog output requested an unknown helper.",
        { helper },
      );
    }
    return `const ${binding} = ${local};`;
  });
  return `${STANDALONE_RUNTIME_IMPORT}\n${body}`;
}

function auditRawSource(source) {
  assertExpectedExports(source);
  const withoutReviewedRequires = source.replace(
    /^const\s+[A-Za-z_$][\w$]*\s*=\s*require\("ajv\/dist\/runtime\/ucs2length"\)\.default;$/gmu,
    "",
  );
  assertNoExecutableLoading(withoutReviewedRequires, "raw");
}

function auditFinalSource(source) {
  assertExpectedExports(source);
  assertNoExecutableLoading(source, "formatted");
  const imports = source.split("\n").filter((line) => /^\s*import\b/u.test(line));
  if (imports.length !== 1 || imports[0] !== STANDALONE_RUNTIME_IMPORT) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_IMPORT_MISMATCH",
      "Generated Catalog output must contain one reviewed local static import.",
      { expected: [STANDALONE_RUNTIME_IMPORT], actual: imports },
    );
  }
}

function exactSchemaBytes(schemaBytes) {
  if (schemaBytes !== undefined) return Buffer.from(schemaBytes);
  return readFile(DEFAULT_PACKAGE_PREFLIGHT_CATALOG_SCHEMA_PATH);
}

export async function generatePackagePreflightCatalogGuard({ schemaBytes } = {}) {
  assertToolVersions();
  const bytes = Buffer.from(await exactSchemaBytes(schemaBytes));
  const { schema, actualSha256 } = parseAndAuditSchema(bytes);
  const ajv = new Ajv2020(AJV_OPTIONS);
  ajv.addSchema(schema);
  let rawSource;
  try {
    rawSource = standaloneCode(ajv, {
      [EXPORT_NAME]: PACKAGE_PREFLIGHT_CATALOG_SCHEMA_SPEC.schemaId,
    });
  } catch (error) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_GENERATION_FAILED",
      "Ajv could not compile the reviewed fail-fast Catalog guard.",
      { cause: String(error) },
    );
  }
  auditRawSource(rawSource);
  const transformed = transformRuntimeHelpers(rawSource);
  assertNoExecutableLoading(transformed, "transformed");
  const formatted = await format(`${GENERATED_BANNER}\n${transformed}`, {
    endOfLine: "lf",
    parser: "typescript",
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "all",
  });
  const source = `${formatted.replaceAll("\r\n", "\n").trimEnd()}\n`;
  auditFinalSource(source);
  const outputBytes = Buffer.from(source, "utf8");
  return Object.freeze({
    outputBytes,
    outputSha256: sha256(outputBytes),
    schema: Object.freeze({
      schemaFile: PACKAGE_PREFLIGHT_CATALOG_SCHEMA_SPEC.schemaFile,
      schemaId: PACKAGE_PREFLIGHT_CATALOG_SCHEMA_SPEC.schemaId,
      sha256: actualSha256,
      bytes: bytes.byteLength,
    }),
    exports: Object.freeze([EXPORT_NAME]),
    allErrors: false,
    runtimeImports: Object.freeze([STANDALONE_RUNTIME_SPECIFIER]),
    localHelpers: Object.freeze([...EXPECTED_RUNTIME_HELPERS.values()].sort(compareStrings)),
  });
}

async function ensureRealDirectoryChain(directoryPath) {
  const relativePath = path.relative(WORKSPACE_ROOT, path.resolve(directoryPath));
  if (
    path.isAbsolute(relativePath) ||
    relativePath === ".." ||
    relativePath.startsWith(`..${path.sep}`)
  ) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_PATH_ESCAPE",
      "Generated Catalog guard path escapes the workspace.",
    );
  }
  let current = WORKSPACE_ROOT;
  for (const segment of relativePath === "" ? [] : relativePath.split(path.sep)) {
    current = path.join(current, segment);
    const stats = await lstat(current).catch(() => undefined);
    if (stats === undefined) {
      await mkdir(current);
    } else if (!stats.isDirectory() || stats.isSymbolicLink()) {
      fail(
        "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_UNSAFE",
        "Generated Catalog guard directories must be real directories.",
      );
    }
  }
}

async function assertRegularTarget(targetPath) {
  const stats = await lstat(targetPath).catch(() => undefined);
  if (stats !== undefined && (!stats.isFile() || stats.isSymbolicLink())) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_UNSAFE",
      "Generated Catalog guard output must be a regular non-symbolic file.",
    );
  }
}

export async function writePackagePreflightCatalogGuardArtifact(
  generated,
  { outputPath = DEFAULT_PACKAGE_PREFLIGHT_CATALOG_GUARD_PATH } = {},
) {
  await ensureRealDirectoryChain(path.dirname(outputPath));
  await assertRegularTarget(outputPath);
  await writeFile(outputPath, generated.outputBytes);
  return Object.freeze({ outputPath });
}

async function readTrackedOutput(outputPath) {
  const directory = path.dirname(outputPath);
  const entries = await readdir(directory, { withFileTypes: true });
  const allowed = ["bundle-verification-guards.ts", path.basename(outputPath)].sort(compareStrings);
  const actual = entries.map(({ name }) => name).sort(compareStrings);
  if (
    actual.length !== allowed.length ||
    actual.some((name, index) => name !== allowed[index]) ||
    entries.some((entry) => !entry.isFile())
  ) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_INVENTORY_MISMATCH",
      "Generated guard directory contains an unexpected entry.",
      { expected: allowed, actual },
    );
  }
  const stats = await lstat(outputPath);
  if (!stats.isFile() || stats.isSymbolicLink()) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_UNSAFE",
      "Tracked Catalog guard must be a regular non-symbolic file.",
    );
  }
  return readFile(outputPath);
}

export async function verifyPackagePreflightCatalogGuardArtifact({
  schemaBytes,
  outputBytes,
  outputPath = DEFAULT_PACKAGE_PREFLIGHT_CATALOG_GUARD_PATH,
} = {}) {
  const first = await generatePackagePreflightCatalogGuard({ schemaBytes });
  const second = await generatePackagePreflightCatalogGuard({ schemaBytes });
  if (!first.outputBytes.equals(second.outputBytes)) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_GENERATION_NONDETERMINISTIC",
      "Independent fail-fast Catalog guard generations differ in bytes.",
      { first: first.outputSha256, second: second.outputSha256 },
    );
  }
  const actual =
    outputBytes === undefined ? await readTrackedOutput(outputPath) : Buffer.from(outputBytes);
  if (!first.outputBytes.equals(actual)) {
    fail(
      "PACKAGE_PREFLIGHT_CATALOG_GUARD_OUTPUT_DRIFT",
      "Tracked fail-fast Catalog guard differs from deterministic regeneration.",
      { expected: first.outputSha256, actual: sha256(actual) },
    );
  }
  return Object.freeze({
    result: "PASS",
    protocol: "0.1.0",
    tools: Object.freeze({ ajv: AJV_VERSION, prettier: PRETTIER_VERSION }),
    schemaRoots: 1,
    schemas: Object.freeze([first.schema]),
    exports: first.exports,
    allErrors: first.allErrors,
    runtimeCompilation: false,
    dynamicLoading: false,
    networkAccess: false,
    runtimeImports: first.runtimeImports,
    localHelpers: first.localHelpers,
    outputSha256: first.outputSha256,
    outputBytes: first.outputBytes.byteLength,
  });
}
