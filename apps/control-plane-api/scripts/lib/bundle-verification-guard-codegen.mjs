export class BundleVerificationGuardCodegenError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = "BundleVerificationGuardCodegenError";
    this.code = code;
    this.details = Object.freeze({ ...details });
  }
}

function fail(code, message, details = {}) {
  throw new BundleVerificationGuardCodegenError(code, message, details);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function compareStrings(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function assertToolVersions() {
  const actual = Object.freeze({
    ajv: require("ajv/package.json").version,
    prettier: require("prettier/package.json").version,
  });
  const expected = Object.freeze({ ajv: AJV_VERSION, prettier: PRETTIER_VERSION });
  if (actual.ajv !== expected.ajv || actual.prettier !== expected.prettier) {
    fail(
      "BUNDLE_GUARD_TOOL_VERSION_MISMATCH",
      "Bundle-verification guard generation requires the exact reviewed tool versions.",
      { expected, actual },
    );
  }
}

function assertSchemaInventory(schemaFiles) {
  if (!(schemaFiles instanceof Map)) {
    fail("BUNDLE_GUARD_SCHEMA_INVENTORY_MISMATCH", "Schema input must be one exact Map.");
  }
  const expected = BUNDLE_VERIFICATION_GUARD_SCHEMA_SPECS.map(({ schemaFile }) => schemaFile).sort(
    compareStrings,
  );
  const actual = [...schemaFiles.keys()].sort(compareStrings);
  if (
    actual.length !== expected.length ||
    actual.some((schemaFile, index) => schemaFile !== expected[index])
  ) {
    fail(
      "BUNDLE_GUARD_SCHEMA_INVENTORY_MISMATCH",
      "Guard generation received an input other than the two reviewed frozen roots.",
      { expected, actual },
    );
  }
}

function auditSchemaReferences(schema, schemaFile) {
  const pending = [{ value: schema, pointer: "#" }];
  while (pending.length > 0) {
    const current = pending.pop();
    if (current === undefined) break;
    const { value, pointer } = current;
    if (value === null || typeof value !== "object") continue;
    if (!Array.isArray(value)) {
      for (const keyword of ["$ref", "$dynamicRef"]) {
        const reference = value[keyword];
        if (typeof reference === "string" && reference !== "" && !reference.startsWith("#")) {
          fail(
            "BUNDLE_GUARD_EXTERNAL_REFERENCE_FORBIDDEN",
            "Frozen root schemas may not resolve external references.",
            { schemaFile, pointer: `${pointer}/${keyword}`, reference },
          );
        }
      }
      if (Object.hasOwn(value, "$schema") && value.$schema !== DRAFT_2020_12_ID) {
        fail(
          "BUNDLE_GUARD_DIALECT_MISMATCH",
          "Frozen roots may not change the reviewed Draft 2020-12 dialect.",
          { schemaFile, pointer: `${pointer}/$schema`, actual: value.$schema },
        );
      }
    }
    const entries = Array.isArray(value)
      ? value.map((child, index) => [String(index), child])
      : Object.entries(value);
    for (const [key, child] of entries.reverse()) {
      pending.push({
        value: child,
        pointer: `${pointer}/${key.replaceAll("~", "~0").replaceAll("/", "~1")}`,
      });
    }
  }
}

function parseAndAuditSchema(schemaBytes, spec) {
  const actualSha256 = sha256(schemaBytes);
  let schema;
  try {
    schema = JSON.parse(Buffer.from(schemaBytes).toString("utf8"));
  } catch {
    fail("BUNDLE_GUARD_SCHEMA_PARSE_FAILED", "A frozen guard schema is not valid JSON.", {
      schemaFile: spec.schemaFile,
    });
  }
  if (
    schema === null ||
    typeof schema !== "object" ||
    Array.isArray(schema) ||
    schema.$id !== spec.schemaId ||
    schema.$schema !== DRAFT_2020_12_ID ||
    schema.title !== spec.schemaTitle ||
    actualSha256 !== spec.schemaSha256
  ) {
    fail(
      "BUNDLE_GUARD_SCHEMA_IDENTITY_MISMATCH",
      "A frozen guard root no longer has its exact reviewed bytes and identity.",
      {
        schemaFile: spec.schemaFile,
        expected: {
          $id: spec.schemaId,
          $schema: DRAFT_2020_12_ID,
          title: spec.schemaTitle,
          sha256: spec.schemaSha256,
        },
        actual: {
          $id: schema?.$id,
          $schema: schema?.$schema,
          title: schema?.title,
          sha256: actualSha256,
        },
      },
    );
  }
  auditSchemaReferences(schema, spec.schemaFile);
  return { schema, actualSha256 };
}

function exportNames(source) {
  const declarations = [...source.matchAll(/^export\s+const\s+([A-Za-z_$][\w$]*)\s*=/gmu)].map(
    (match) => match[1],
  );
  if ([...source.matchAll(/^export\b/gmu)].length !== declarations.length) {
    fail(
      "BUNDLE_GUARD_EXPORT_MISMATCH",
      "Standalone output contains an export form outside the reviewed named constants.",
    );
  }
  return declarations;
}

function assertExpectedExports(source) {
  const actual = exportNames(source).sort(compareStrings);
  const expected = [...EXPECTED_EXPORTS].sort(compareStrings);
  if (actual.length !== expected.length || actual.some((name, index) => name !== expected[index])) {
    fail(
      "BUNDLE_GUARD_EXPORT_MISMATCH",
      "Standalone output exports a validator set outside the three reviewed guards.",
      { expected, actual },
    );
  }
}

function assertNoExecutableLoading(source, phase) {
  const violations = [];
  if (/\brequire\s*\(/u.test(source)) violations.push("require");
  if (/\beval\s*\(/u.test(source)) violations.push("eval");
  if (/\bnew\s+Function\b/u.test(source)) violations.push("new-Function");
  if (/\bimport\s*\(/u.test(source)) violations.push("dynamic-import");
  if (
    source.includes(WORKSPACE_ROOT) ||
    source.includes(DEFAULT_BUNDLE_VERIFICATION_GUARD_SCHEMA_DIRECTORY) ||
    source.includes("file://")
  ) {
    violations.push("absolute-path");
  }
  const specifiers = [...source.matchAll(/\bfrom\s+["']([^"']+)["']/gu)].map((match) => match[1]);
  if (
    specifiers.some((specifier) => path.isAbsolute(specifier) || /^[A-Za-z]:[\\/]/u.test(specifier))
  ) {
    violations.push("absolute-module-path");
  }
  if (violations.length > 0) {
    fail(
      "BUNDLE_GUARD_CODE_LOADING_VIOLATION",
      "Standalone guard output contains a forbidden runtime-loading construct.",
      { phase, violations: [...new Set(violations)].sort(compareStrings) },
    );
  }
}

function transformRuntimeHelpers(rawSource) {
  const requirePattern = /^const\s+([A-Za-z_$][\w$]*)\s*=\s*require\("([^"]+)"\)\.default;$/gmu;
  const matches = [...rawSource.matchAll(requirePattern)];
  const actual = matches.map((match) => match[2]).sort(compareStrings);
  const expected = [...EXPECTED_RUNTIME_HELPERS.keys()].sort(compareStrings);
  if (
    actual.length !== expected.length ||
    actual.some((helper, index) => helper !== expected[index])
  ) {
    fail(
      "BUNDLE_GUARD_HELPER_MISMATCH",
      "Standalone output requested helpers outside the reviewed local allowlist.",
      { expected, actual },
    );
  }
  const transformedBody = rawSource.replace(requirePattern, (_line, binding, helper) => {
    const local = EXPECTED_RUNTIME_HELPERS.get(helper);
    if (local === undefined) {
      fail("BUNDLE_GUARD_HELPER_MISMATCH", "Standalone output requested an unknown helper.", {
        helper,
      });
    }
    return `const ${binding} = ${local};`;
  });
  return `${STANDALONE_RUNTIME_IMPORT}\n${transformedBody}`;
}

function auditRawSource(source) {
  assertExpectedExports(source);
  const withoutReviewedRequires = source.replace(
    /^const\s+[A-Za-z_$][\w$]*\s*=\s*require\("(?:ajv\/dist\/runtime\/(?:ucs2length|equal))"\)\.default;$/gmu,
    "",
  );
  assertNoExecutableLoading(withoutReviewedRequires, "raw");
}

function auditFinalSource(source) {
  assertExpectedExports(source);
  assertNoExecutableLoading(source, "formatted");
  const imports = source.split("\n").filter((line) => /^\s*import\b/u.test(line));
  if (imports.length !== 1 || imports[0] !== STANDALONE_RUNTIME_IMPORT) {
    fail(
      "BUNDLE_GUARD_IMPORT_MISMATCH",
      "Generated output must contain exactly one reviewed local static import.",
      { expected: [STANDALONE_RUNTIME_IMPORT], actual: imports },
    );
  }
}

function exportMap() {
  return Object.fromEntries([
    ...BUNDLE_VERIFICATION_GUARD_SCHEMA_SPECS.map(({ exportName, schemaId }) => [
      exportName,
      schemaId,
    ]),
    [META_SCHEMA_EXPORT.exportName, META_SCHEMA_EXPORT.schemaId],
  ]);
}

export async function loadBundleVerificationGuardSchemaFiles(
  schemaDirectory = DEFAULT_BUNDLE_VERIFICATION_GUARD_SCHEMA_DIRECTORY,
) {
  const files = new Map();
  for (const { schemaFile } of BUNDLE_VERIFICATION_GUARD_SCHEMA_SPECS) {
    files.set(schemaFile, await readFile(path.join(schemaDirectory, schemaFile)));
  }
  return files;
}

export async function generateBundleVerificationGuards({ schemaFiles } = {}) {
  assertToolVersions();
  const inputFiles = schemaFiles ?? (await loadBundleVerificationGuardSchemaFiles());
  assertSchemaInventory(inputFiles);
  const ajv = new Ajv2020(AJV_OPTIONS);
  const schemas = [];
  for (const spec of BUNDLE_VERIFICATION_GUARD_SCHEMA_SPECS) {
    const input = inputFiles.get(spec.schemaFile);
    if (input === undefined) {
      fail("BUNDLE_GUARD_SCHEMA_INVENTORY_MISMATCH", "A reviewed guard root is absent.", {
        schemaFile: spec.schemaFile,
      });
    }
    const bytes = Buffer.from(input);
    const { schema, actualSha256 } = parseAndAuditSchema(bytes, spec);
    ajv.addSchema(schema);
    schemas.push(
      Object.freeze({
        schemaFile: spec.schemaFile,
        schemaId: spec.schemaId,
        sha256: actualSha256,
        bytes: bytes.byteLength,
        exportName: spec.exportName,
      }),
    );
  }

  let rawSource;
  try {
    rawSource = standaloneCode(ajv, exportMap());
  } catch (error) {
    fail(
      "BUNDLE_GUARD_GENERATION_FAILED",
      "Ajv could not compile the reviewed fail-fast guard set.",
      { cause: String(error) },
    );
  }
  auditRawSource(rawSource);
  const transformed = transformRuntimeHelpers(rawSource);
  assertNoExecutableLoading(transformed, "transformed");
  const formatted = await format(`${GENERATED_BANNER}\n${transformed}`, {
    endOfLine: "lf",
    parser: "typescript",
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "all",
  });
  const source = `${formatted.replaceAll("\r\n", "\n").trimEnd()}\n`;
  auditFinalSource(source);
  const outputBytes = Buffer.from(source, "utf8");
  return Object.freeze({
    outputBytes,
    outputSha256: sha256(outputBytes),
    schemas: Object.freeze(schemas),
    exports: EXPECTED_EXPORTS,
    allErrors: false,
    runtimeImports: Object.freeze([STANDALONE_RUNTIME_SPECIFIER]),
    localHelpers: Object.freeze([...EXPECTED_RUNTIME_HELPERS.values()].sort(compareStrings)),
  });
}

async function ensureRealDirectoryChain(workspaceRoot, directoryPath) {
  const root = path.resolve(workspaceRoot);
  const directory = path.resolve(directoryPath);
  const relative = path.relative(root, directory);
  if (path.isAbsolute(relative) || relative === ".." || relative.startsWith(`..${path.sep}`)) {
    fail("BUNDLE_GUARD_OUTPUT_PATH_ESCAPE", "Generated guard path escapes the workspace.", {
      path: directory,
    });
  }
  let current = root;
  for (const segment of relative === "" ? [] : relative.split(path.sep)) {
    current = path.join(current, segment);
    try {
      const stats = await lstat(current);
      if (!stats.isDirectory() || stats.isSymbolicLink()) {
        fail(
          "BUNDLE_GUARD_OUTPUT_UNSUPPORTED_ENTRY",
          "Generated guard directories must be real directories.",
          { path: current },
        );
      }
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      await mkdir(current);
    }
  }
  return directory;
}

async function assertRegularTarget(targetPath) {
  try {
    const stats = await lstat(targetPath);
    if (!stats.isFile() || stats.isSymbolicLink()) {
      fail(
        "BUNDLE_GUARD_OUTPUT_UNSUPPORTED_ENTRY",
        "Generated guard output must be a regular non-symbolic file.",
        { path: targetPath },
      );
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
}

export async function writeBundleVerificationGuardArtifact(
  generated,
  { workspaceRoot = WORKSPACE_ROOT, outputPath = DEFAULT_BUNDLE_VERIFICATION_GUARD_PATH } = {},
) {
  const directory = await ensureRealDirectoryChain(workspaceRoot, path.dirname(outputPath));
  const safePath = path.join(directory, path.basename(outputPath));
  await assertRegularTarget(safePath);
  await writeFile(safePath, generated.outputBytes);
  return Object.freeze({ outputPath: safePath });
}

async function readTrackedOutput(outputPath) {
  const directory = path.dirname(outputPath);
  const directoryStats = await lstat(directory).catch(() => undefined);
  if (
    directoryStats === undefined ||
    !directoryStats.isDirectory() ||
    directoryStats.isSymbolicLink()
  ) {
    fail("BUNDLE_GUARD_OUTPUT_MISSING", "Generated guard directory is absent or unsafe.");
  }
  const entries = await readdir(directory, { withFileTypes: true });
  const expected = path.basename(outputPath);
  if (entries.length !== 1 || entries[0]?.name !== expected || !entries[0].isFile()) {
    fail(
      "BUNDLE_GUARD_OUTPUT_INVENTORY_MISMATCH",
      "Generated guard directory must contain exactly the reviewed module.",
      { expected: [expected], actual: entries.map(({ name }) => name).sort(compareStrings) },
    );
  }
  const stats = await lstat(outputPath);
  if (!stats.isFile() || stats.isSymbolicLink()) {
    fail(
      "BUNDLE_GUARD_OUTPUT_UNSUPPORTED_ENTRY",
      "Generated guard output must be a regular non-symbolic file.",
    );
  }
  return readFile(outputPath);
}

export async function verifyBundleVerificationGuardArtifact({
  schemaFiles,
  outputBytes,
  outputPath = DEFAULT_BUNDLE_VERIFICATION_GUARD_PATH,
} = {}) {
  const first = await generateBundleVerificationGuards({ schemaFiles });
  const second = await generateBundleVerificationGuards({ schemaFiles });
  if (!first.outputBytes.equals(second.outputBytes)) {
    fail(
      "BUNDLE_GUARD_GENERATION_NONDETERMINISTIC",
      "Independent fail-fast guard generations differ in bytes.",
      { first: first.outputSha256, second: second.outputSha256 },
    );
  }
  const actual =
    outputBytes === undefined ? await readTrackedOutput(outputPath) : Buffer.from(outputBytes);
  if (!first.outputBytes.equals(actual)) {
    fail(
      "BUNDLE_GUARD_OUTPUT_DRIFT",
      "Tracked fail-fast guard bytes differ from deterministic regeneration.",
      { expected: first.outputSha256, actual: sha256(actual) },
    );
  }
  return Object.freeze({
    result: "PASS",
    protocol: "0.1.0",
    tools: Object.freeze({ ajv: AJV_VERSION, prettier: PRETTIER_VERSION }),
    schemaRoots: BUNDLE_VERIFICATION_GUARD_SCHEMA_SPECS.length,
    schemas: first.schemas,
    exports: first.exports,
    allErrors: first.allErrors,
    runtimeCompilation: false,
    dynamicLoading: false,
    networkAccess: false,
    runtimeImports: first.runtimeImports,
    localHelpers: first.localHelpers,
    outputSha256: first.outputSha256,
    outputBytes: first.outputBytes.byteLength,
  });
}
