/** Stable internal failure raised by structural validator generation and verification. */
export class StructuralValidatorCodegenError extends Error {
  /**
   * @param {string} code stable failure code
   * @param {string} message human-readable failure summary
   * @param {Record<string, unknown>} [details] structured failure context
   */
  constructor(code, message, details = {}) {
    super(message);
    this.name = "StructuralValidatorCodegenError";
    this.code = code;
    this.details = details;
  }
}

function fail(code, message, details = {}) {
  throw new StructuralValidatorCodegenError(code, message, details);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function compareStrings(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function assertToolVersions() {
  const actualAjvVersion = require("ajv/package.json").version;
  const actualPrettierVersion = require("prettier/package.json").version;
  if (actualAjvVersion !== AJV_VERSION || actualPrettierVersion !== PRETTIER_VERSION) {
    fail(
      "STRUCTURAL_CODEGEN_TOOL_VERSION_MISMATCH",
      "Structural validator generation requires the reviewed, pinned tool versions.",
      {
        expected: { ajv: AJV_VERSION, prettier: PRETTIER_VERSION },
        actual: { ajv: actualAjvVersion, prettier: actualPrettierVersion },
      },
    );
  }
}

function assertSchemaInventory(schemaFiles) {
  const expected = STRUCTURAL_SCHEMA_SPECS.map(({ schemaFile }) => schemaFile).sort(compareStrings);
  const actual = [...schemaFiles.keys()].sort(compareStrings);
  const missing = expected.filter((schemaFile) => !actual.includes(schemaFile));
  const unexpected = actual.filter((schemaFile) => !expected.includes(schemaFile));
  if (missing.length > 0 || unexpected.length > 0) {
    fail(
      "STRUCTURAL_SCHEMA_INVENTORY_MISMATCH",
      "Structural generation received a schema inventory other than the three reviewed roots.",
      { missing, unexpected },
    );
  }
}

function parseAndAuditSchema(schemaBytes, spec) {
  const actualSha256 = sha256(schemaBytes);
  let schema;
  try {
    schema = JSON.parse(schemaBytes.toString("utf8"));
  } catch (error) {
    fail("STRUCTURAL_SCHEMA_PARSE_FAILED", "A frozen schema is not valid JSON.", {
      schemaFile: spec.schemaFile,
      cause: String(error),
    });
  }

  if (
    schema === null ||
    typeof schema !== "object" ||
    Array.isArray(schema) ||
    schema.$id !== spec.schemaId ||
    schema.$schema !== DRAFT_2020_12_ID ||
    schema.title !== spec.schemaTitle
  ) {
    fail(
      "STRUCTURAL_SCHEMA_IDENTITY_MISMATCH",
      "A frozen schema root no longer has its reviewed identity and dialect.",
      {
        schemaFile: spec.schemaFile,
        expected: { $id: spec.schemaId, $schema: DRAFT_2020_12_ID, title: spec.schemaTitle },
        actual: { $id: schema?.$id, $schema: schema?.$schema, title: schema?.title },
      },
    );
  }

  auditSchemaReferences(schema, spec.schemaFile);
  if (actualSha256 !== spec.schemaSha256) {
    fail(
      "STRUCTURAL_SCHEMA_BYTES_MISMATCH",
      "A frozen schema differs from the reviewed DESEN 0.1.0 bytes.",
      { schemaFile: spec.schemaFile, expected: spec.schemaSha256, actual: actualSha256 },
    );
  }
  return { schema, actualSha256 };
}

function auditSchemaReferences(schema, schemaFile) {
  const pending = [{ value: schema, pointer: "#" }];
  while (pending.length > 0) {
    const current = pending.pop();
    if (current === undefined) break;
    const { value, pointer } = current;
    if (value === null || typeof value !== "object") continue;

    if (!Array.isArray(value)) {
      for (const keyword of ["$ref", "$dynamicRef"]) {
        const reference = value[keyword];
        if (typeof reference === "string" && reference !== "" && !reference.startsWith("#")) {
          fail(
            "STRUCTURAL_EXTERNAL_REFERENCE_FORBIDDEN",
            "Frozen root schemas may not make network or filesystem reference resolutions.",
            { schemaFile, pointer: `${pointer}/${keyword}`, reference },
          );
        }
      }
      if ("$schema" in value && value.$schema !== DRAFT_2020_12_ID) {
        fail(
          "STRUCTURAL_DIALECT_MISMATCH",
          "Frozen schemas may not switch away from the reviewed Draft 2020-12 dialect.",
          { schemaFile, pointer: `${pointer}/$schema`, actual: value.$schema },
        );
      }
    }

    const entries = Array.isArray(value)
      ? value.map((child, index) => [String(index), child])
      : Object.entries(value);
    for (const [key, child] of entries.reverse()) {
      const escapedKey = key.replaceAll("~", "~0").replaceAll("/", "~1");
      pending.push({ value: child, pointer: `${pointer}/${escapedKey}` });
    }
  }
}

function getExportNames(source) {
  const declarations = [...source.matchAll(/^export\s+const\s+([A-Za-z_$][\w$]*)\s*=/gm)].map(
    (match) => match[1],
  );
  const exportStatements = [...source.matchAll(/^export\b/gm)];
  if (exportStatements.length !== declarations.length) {
    fail(
      "STRUCTURAL_STANDALONE_UNEXPECTED_EXPORT_SYNTAX",
      "Standalone output contains an export form outside the reviewed named constants.",
    );
  }
  return declarations;
}

function assertExpectedExports(source) {
  const actual = getExportNames(source).sort(compareStrings);
  const expected = [...EXPECTED_EXPORTS].sort(compareStrings);
  if (actual.length !== expected.length || actual.some((name, index) => name !== expected[index])) {
    fail(
      "STRUCTURAL_STANDALONE_EXPORT_MISMATCH",
      "Standalone output exports a validator set other than the four reviewed entry points.",
      { expected, actual },
    );
  }
}

function assertNoExecutableCodeLoading(source, phase) {
  const violations = [];
  if (/\brequire\s*\(/u.test(source)) violations.push("require");
  if (/\beval\s*\(/u.test(source)) violations.push("eval");
  if (/\bnew\s+Function\b/u.test(source)) violations.push("new-Function");
  if (/\bimport\s*\(/u.test(source)) violations.push("dynamic-import");
  if (source.includes(WORKSPACE_ROOT) || source.includes(DEFAULT_STRUCTURAL_SCHEMA_DIRECTORY)) {
    violations.push("workspace-absolute-path");
  }

  const moduleSpecifiers = [
    ...source.matchAll(/\bfrom\s+["']([^"']+)["']/gu),
    ...source.matchAll(/\brequire\s*\(\s*["']([^"']+)["']\s*\)/gu),
  ].map((match) => match[1]);
  if (
    moduleSpecifiers.some(
      (specifier) => path.isAbsolute(specifier) || /^[A-Za-z]:[\\/]/u.test(specifier),
    ) ||
    source.includes("file://")
  ) {
    violations.push("absolute-module-path");
  }

  if (violations.length > 0) {
    fail(
      "STRUCTURAL_STANDALONE_CODE_LOADING_VIOLATION",
      "Standalone output contains a forbidden code-loading or path construct.",
      { phase, violations: [...new Set(violations)].sort(compareStrings) },
    );
  }
}

function transformReviewedRuntimeHelpers(rawSource) {
  const requirePattern = /^const\s+([A-Za-z_$][\w$]*)\s*=\s*require\("([^"]+)"\)\.default;$/gmu;
  const matches = [...rawSource.matchAll(requirePattern)];
  const actualHelpers = matches.map((match) => match[2]).sort(compareStrings);
  const expectedHelpers = [...EXPECTED_RUNTIME_HELPERS.keys()].sort(compareStrings);

  if (
    actualHelpers.length !== expectedHelpers.length ||
    actualHelpers.some((helper, index) => helper !== expectedHelpers[index])
  ) {
    fail(
      "STRUCTURAL_STANDALONE_HELPER_MISMATCH",
      "Ajv standalone output uses runtime helpers outside the reviewed allowlist.",
      { expected: expectedHelpers, actual: actualHelpers },
    );
  }

  const transformedBody = rawSource.replace(requirePattern, (_line, binding, helper) => {
    const localHelper = EXPECTED_RUNTIME_HELPERS.get(helper);
    if (localHelper === undefined) {
      fail(
        "STRUCTURAL_STANDALONE_HELPER_MISMATCH",
        "Ajv standalone output requested an unreviewed runtime helper.",
        { helper },
      );
    }
    return `const ${binding} = ${localHelper};`;
  });
  const transformed = `${STANDALONE_RUNTIME_IMPORT}\n${transformedBody}`;

  const importLines = transformed.split("\n").filter((line) => /^\s*import\b/u.test(line));
  if (importLines.length !== 1 || importLines[0] !== STANDALONE_RUNTIME_IMPORT) {
    fail(
      "STRUCTURAL_STANDALONE_IMPORT_MISMATCH",
      "Transformed standalone output does not have exactly the reviewed local helper import.",
      { expected: [STANDALONE_RUNTIME_IMPORT], actual: importLines },
    );
  }

  return transformed;
}

function auditRawStandaloneSource(rawSource) {
  assertExpectedExports(rawSource);

  const withoutReviewedRequires = rawSource.replace(
    /^const\s+[A-Za-z_$][\w$]*\s*=\s*require\("(?:ajv\/dist\/runtime\/(?:ucs2length|equal))"\)\.default;$/gmu,
    "",
  );
  assertNoExecutableCodeLoading(withoutReviewedRequires, "raw");
}

function auditFinalStandaloneSource(source) {
  assertExpectedExports(source);
  assertNoExecutableCodeLoading(source, "formatted");

  const importLines = source.split("\n").filter((line) => /^\s*import\b/u.test(line));
  if (importLines.length !== 1 || importLines[0] !== STANDALONE_RUNTIME_IMPORT) {
    fail(
      "STRUCTURAL_STANDALONE_IMPORT_MISMATCH",
      "Formatted output changed the exact reviewed static import declaration.",
      { expected: [STANDALONE_RUNTIME_IMPORT], actual: importLines },
    );
  }
}

function createAjv() {
  return new Ajv2020(AJV_OPTIONS);
}

function buildStandaloneExportMap() {
  return Object.fromEntries([
    ...STRUCTURAL_SCHEMA_SPECS.map(({ exportName, schemaId }) => [exportName, schemaId]),
    [META_SCHEMA_EXPORT.exportName, META_SCHEMA_EXPORT.schemaId],
  ]);
}

/**
 * Reads the three frozen root schemas without normalizing or rewriting their bytes.
 *
 * @param {string} [schemaDirectory] alternate exact-name schema directory for negative tests
 * @returns {Promise<Map<string, Buffer>>} frozen schema bytes keyed by reviewed filename
 */
export async function loadStructuralValidatorSchemaFiles(
  schemaDirectory = DEFAULT_STRUCTURAL_SCHEMA_DIRECTORY,
) {
  const files = new Map();
  for (const { schemaFile } of STRUCTURAL_SCHEMA_SPECS) {
    files.set(schemaFile, await readFile(path.join(schemaDirectory, schemaFile)));
  }
  return files;
}

/**
 * Deterministically compiles the exact frozen root schemas and Draft 2020-12 meta-schema to ESM.
 *
 * The returned module is audited to contain only four named validators, one allowlisted local
 * runtime import with two reviewed helper bindings, and no runtime compilation, dynamic loading,
 * or absolute workspace path.
 *
 * @param {{ schemaFiles?: Map<string, Uint8Array | string> }} [options] injectable schema bytes for negative tests
 * @returns {Promise<Readonly<{ outputBytes: Buffer; outputSha256: string; schemas: readonly Readonly<Record<string, unknown>>[]; exports: readonly string[]; runtimeImports: readonly string[]; localHelpers: readonly string[] }>>}
 */
export async function generateStructuralValidators({ schemaFiles } = {}) {
  assertToolVersions();
  const inputFiles = schemaFiles ?? (await loadStructuralValidatorSchemaFiles());
  assertSchemaInventory(inputFiles);

  const ajv = createAjv();
  const schemas = [];
  for (const spec of STRUCTURAL_SCHEMA_SPECS) {
    const value = inputFiles.get(spec.schemaFile);
    if (value === undefined) {
      fail("STRUCTURAL_SCHEMA_INVENTORY_MISMATCH", "A reviewed root schema is missing.", {
        schemaFile: spec.schemaFile,
      });
    }
    const schemaBytes = Buffer.from(value);
    const { schema, actualSha256 } = parseAndAuditSchema(schemaBytes, spec);
    ajv.addSchema(schema);
    schemas.push(
      Object.freeze({
        schemaFile: spec.schemaFile,
        schemaId: spec.schemaId,
        sha256: actualSha256,
        bytes: schemaBytes.byteLength,
        exportName: spec.exportName,
      }),
    );
  }

  let rawSource;
  try {
    rawSource = standaloneCode(ajv, buildStandaloneExportMap());
  } catch (error) {
    fail(
      "STRUCTURAL_STANDALONE_GENERATION_FAILED",
      "Ajv could not compile the reviewed structural validators.",
      { cause: String(error) },
    );
  }

  auditRawStandaloneSource(rawSource);
  const transformed = transformReviewedRuntimeHelpers(rawSource);
  assertNoExecutableCodeLoading(transformed, "transformed");

  const formatted = await format(`${GENERATED_BANNER}\n${transformed}`, {
    endOfLine: "lf",
    parser: "typescript",
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "all",
  });
  const normalized = `${formatted.replaceAll("\r\n", "\n").trimEnd()}\n`;
  auditFinalStandaloneSource(normalized);

  const outputBytes = Buffer.from(normalized, "utf8");
  return Object.freeze({
    outputBytes,
    outputSha256: sha256(outputBytes),
    schemas: Object.freeze(schemas),
    exports: EXPECTED_EXPORTS,
    runtimeImports: Object.freeze([STANDALONE_RUNTIME_SPECIFIER]),
    localHelpers: Object.freeze([...EXPECTED_RUNTIME_HELPERS.values()].sort(compareStrings)),
  });
}

async function ensureRealDirectoryChain(workspaceRoot, directoryPath) {
  const resolvedWorkspaceRoot = path.resolve(workspaceRoot);
  const resolvedDirectoryPath = path.resolve(directoryPath);
  const relativePath = path.relative(resolvedWorkspaceRoot, resolvedDirectoryPath);
  if (
    path.isAbsolute(relativePath) ||
    relativePath === ".." ||
    relativePath.startsWith(`..${path.sep}`)
  ) {
    fail(
      "STRUCTURAL_OUTPUT_PATH_ESCAPE",
      "The structural validator output path escapes the workspace root.",
      { path: resolvedDirectoryPath },
    );
  }

  let currentPath = resolvedWorkspaceRoot;
  const segments = relativePath === "" ? [] : relativePath.split(path.sep);
  for (const segment of ["", ...segments]) {
    if (segment !== "") currentPath = path.join(currentPath, segment);
    let stats;
    try {
      stats = await lstat(currentPath);
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      try {
        await mkdir(currentPath);
      } catch (mkdirError) {
        if (mkdirError?.code !== "EEXIST") throw mkdirError;
      }
      stats = await lstat(currentPath);
    }
    if (!stats.isDirectory() || stats.isSymbolicLink()) {
      fail(
        "STRUCTURAL_OUTPUT_UNSUPPORTED_ENTRY",
        "Generated artifact directories must be real directories, never symlinks.",
        { path: currentPath },
      );
    }
  }
  return resolvedDirectoryPath;
}

async function assertWritableRegularTarget(targetPath) {
  try {
    const stats = await lstat(targetPath);
    if (!stats.isFile() || stats.isSymbolicLink()) {
      fail(
        "STRUCTURAL_OUTPUT_UNSUPPORTED_ENTRY",
        "Generation refuses to replace a symlink or non-regular output target.",
        { path: targetPath },
      );
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
}

/**
 * Writes an in-memory standalone module only to a real, workspace-contained regular file.
 *
 * @param {{ outputBytes: Uint8Array | string }} generated result from generateStructuralValidators
 * @param {{ workspaceRoot?: string; outputPath?: string }} [options] alternate safe targets for tests
 * @returns {Promise<Readonly<{ outputPath: string }>>} written artifact location
 */
export async function writeStructuralValidatorArtifact(
  generated,
  { workspaceRoot = WORKSPACE_ROOT, outputPath = DEFAULT_STRUCTURAL_VALIDATOR_PATH } = {},
) {
  const outputRoot = await ensureRealDirectoryChain(workspaceRoot, path.dirname(outputPath));
  const safeOutputPath = path.join(outputRoot, path.basename(outputPath));
  await assertWritableRegularTarget(safeOutputPath);
  await writeFile(safeOutputPath, generated.outputBytes);
  return Object.freeze({ outputPath: safeOutputPath });
}

async function readTrackedOutput(outputPath) {
  const outputRoot = path.dirname(outputPath);
  let rootStats;
  try {
    rootStats = await lstat(outputRoot);
  } catch (error) {
    fail("STRUCTURAL_OUTPUT_MISSING", "The generated validator directory is missing.", {
      cause: String(error),
    });
  }
  if (!rootStats.isDirectory() || rootStats.isSymbolicLink()) {
    fail(
      "STRUCTURAL_OUTPUT_UNSUPPORTED_ENTRY",
      "The generated validator directory must be a real directory.",
    );
  }

  const entries = await readdir(outputRoot, { withFileTypes: true });
  const expectedFile = path.basename(outputPath);
  const unexpected = entries
    .filter((entry) => entry.name !== expectedFile || !entry.isFile())
    .map((entry) => entry.name)
    .sort(compareStrings);
  if (entries.length !== 1 || unexpected.length > 0) {
    fail(
      "STRUCTURAL_OUTPUT_INVENTORY_MISMATCH",
      "The generated validator directory contains missing, unexpected, or non-regular entries.",
      { expected: [expectedFile], actual: entries.map((entry) => entry.name).sort(compareStrings) },
    );
  }

  const outputStats = await lstat(outputPath);
  if (!outputStats.isFile() || outputStats.isSymbolicLink()) {
    fail(
      "STRUCTURAL_OUTPUT_UNSUPPORTED_ENTRY",
      "The generated validator output must be a regular file, never a symlink.",
      { path: outputPath },
    );
  }
  return readFile(outputPath);
}

/**
 * Regenerates twice, proves byte determinism, and compares the tracked standalone module exactly.
 *
 * @param {{ schemaFiles?: Map<string, Uint8Array | string>; outputBytes?: Uint8Array | string; outputPath?: string }} [options] injectable values for negative tests
 * @returns {Promise<Readonly<{ result: "PASS"; protocol: "0.1.0"; schemaRoots: number; exports: readonly string[]; runtimeImports: readonly string[]; localHelpers: readonly string[]; outputSha256: string; outputBytes: number }>>}
 */
export async function verifyStructuralValidatorArtifact({
  schemaFiles,
  outputBytes,
  outputPath = DEFAULT_STRUCTURAL_VALIDATOR_PATH,
} = {}) {
  const first = await generateStructuralValidators({ schemaFiles });
  const second = await generateStructuralValidators({ schemaFiles });
  if (!first.outputBytes.equals(second.outputBytes)) {
    fail(
      "STRUCTURAL_GENERATION_NONDETERMINISTIC",
      "Independent standalone validator generations differ in bytes.",
      { first: first.outputSha256, second: second.outputSha256 },
    );
  }

  const actualBytes =
    outputBytes === undefined ? await readTrackedOutput(outputPath) : Buffer.from(outputBytes);
  if (!first.outputBytes.equals(actualBytes)) {
    fail(
      "STRUCTURAL_OUTPUT_DRIFT",
      "The tracked standalone validator differs from deterministic regeneration.",
      { expected: first.outputSha256, actual: sha256(actualBytes) },
    );
  }

  return Object.freeze({
    result: "PASS",
    protocol: "0.1.0",
    schemaRoots: STRUCTURAL_SCHEMA_SPECS.length,
    exports: first.exports,
    runtimeImports: first.runtimeImports,
    localHelpers: first.localHelpers,
    outputSha256: first.outputSha256,
    outputBytes: first.outputBytes.byteLength,
  });
}
